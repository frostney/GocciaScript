#!/usr/bin/env python3
"""gen_suggestions.py OUT.inc: GocciaScript's runtime suggestions as a table of (message template, suggestion), for
the G2 GocciaRunner, whose engine throws the same messages without them.

GocciaScript's engine passes a suggestion at each throw site (ThrowTypeError(SErrorX, SSuggestY)). A message is in
the table only when every site that throws it passes the same suggestion, so a message thrown with different
suggestions, or without one somewhere, gets none. Templates keep their %s and %d placeholders, which match any
text; ones with too little literal text to tell apart, or with non-ASCII text, are left out."""
import collections
import glob
import re
import sys

ROOT = 'source/units/'
MIN_LITERAL = 8


def constants():
    found = {}
    for path in glob.glob(ROOT + 'Goccia.Error*.pas'):
        text = open(path, encoding='utf-8').read()
        for m in re.finditer(r"^\s*(S(?:Error|Suggest)\w+)\s*=\s*((?:'(?:[^']|'')*'\s*\+?\s*)+);", text, re.M):
            parts = re.findall(r"'((?:[^']|'')*)'", m.group(2))
            found[m.group(1)] = ''.join(p.replace("''", "'") for p in parts)
    return found


def main():
    out = sys.argv[1]
    names = constants()
    uses = collections.defaultdict(list)
    for path in sorted(glob.glob(ROOT + '*.pas')):
        if path.endswith('.Test.pas') or '/Goccia.Error' in path:
            continue
        text = open(path, encoding='utf-8').read()
        for m in re.finditer(r"Throw\w*Error\s*\((.*?)\)\s*;", text, re.S):
            errors = re.findall(r"\bSError\w+", m.group(1))
            suggestions = re.findall(r"\bSSuggest\w+", m.group(1))
            if len(errors) == 1:
                uses[errors[0]].append(suggestions[0] if len(suggestions) == 1 else None)
    rows = []
    for error, suggestions in uses.items():
        if error not in names or len(set(suggestions)) != 1 or suggestions[0] is None or suggestions[0] not in names:
            continue
        template, suggestion = names[error], names[suggestions[0]]
        literal = re.sub(r'%[sdx]', '', template)
        if len(literal.strip()) < MIN_LITERAL or not (template + suggestion).isascii():
            continue
        rows.append((template, suggestion))
    rows = sorted(set(rows))
    q = lambda s: "'" + s.replace("'", "''") + "'"
    with open(out, 'w') as f:
        f.write('{ generated by scripts/engine/gen_suggestions.py from GocciaScript\'s throw sites: a runtime error\'s\n'
                '  suggestion by its message template (%s and %d match any text) }\n')
        f.write('const\n  RUNTIME_SUGGESTION_COUNT = %d;\n' % len(rows))
        f.write('  RUNTIME_SUGGESTIONS: array[0..%d, 0..1] of string = (\n' % (len(rows) - 1))
        f.write(',\n'.join('    (%s,\n     %s)' % (q(t), q(s)) for t, s in rows))
        f.write('\n  );\n')
    print(len(rows), 'suggestions')


if __name__ == '__main__':
    main()
