#!/bin/sh
# scripts/g2/build.sh: builds the G2 engine (source/g2) against Goccia's front end (source/units) into
# build/g2/g2. Needs FPC 3.3.1 (fpc-toolchain env 3.3.1; G2_FPC_ENV overrides the env command).
# Stage 1 compiles with the JS preludes compiled at start-up, stage 2 runs that binary to snapshot the compiled
# preludes and rebuilds with them embedded (G2.Snapshot). Fails on an FPC native-TLS miscompile (tlsscan.py).
set -u
ROOT=$(cd "$(dirname "$0")/../.." && pwd)
cd "$ROOT"
OUT=build/g2
GEN=$OUT/gen
U=$OUT/units
mkdir -p "$GEN" "$U"
if [ -n "${G2_FPC_ENV:-}" ]; then eval "$G2_FPC_ENV"; else eval "$("$HOME/.local/share/fpc-toolchains/bin/fpc-toolchain" env 3.3.1)"; fi
# the JS preludes as Pascal string constants
python3 scripts/g2/gen_prelude_inc.py source/g2/prelude/builtins5.js "$GEN/G2.Builtins5.inc" Builtins5Src || exit 1
python3 scripts/g2/gen_prelude_inc.py source/g2/prelude/disposal.js "$GEN/G2.Disposal.inc" DisposalSrc || exit 1
python3 scripts/g2/gen_prelude_inc.py source/g2/prelude/iterhelpers.js "$GEN/G2.IterHelpers.inc" IterHelpersSrc || exit 1
python3 scripts/g2/gen_prelude_inc.py source/g2/prelude/regexp.js "$GEN/G2.RegExpPrelude.inc" RegExpSrc || exit 1
python3 scripts/g2/gen_prelude_inc.py source/g2/prelude/temporal.js "$GEN/G2.Temporal.inc" TemporalSrc || exit 1
# Goccia's version include, as build.pas writes it (here into the G2 generated directory)
V=$(git describe --tags --abbrev=0 2>/dev/null | sed 's/^v//'); [ -n "$V" ] && V="$V-dev" || V=0.0.0-dev
printf "// Auto-generated by scripts/g2/build.sh — do not edit\nconst\n  BAKED_VERSION = '%s';\n  BAKED_COMMIT = '%s';\n  BAKED_BUILD_DATE = '%s';\n" \
  "$V" "$(git rev-parse --short HEAD 2>/dev/null || echo unknown)" "$(date +%F)" > "$GEN/Goccia.Version.Generated.inc"
# an empty snapshot until stage 2 has made one
[ -f "$GEN/G2.PreludeSnapshot.inc" ] || printf 'const\n  G2PreludeSnapshotSize = 0;\n  G2PreludeSnapshot: array[0..0] of Byte = (0);\n' > "$GEN/G2.PreludeSnapshot.inc"
cp source/generated/*.res "$U/" 2>/dev/null
compile() {
  fpc -O4 -OoNOFASTMATH -dPRODUCTION -Xs ${G2_EXTRA:-} -Fusource/g2 -Fusource/units -Fusource/shared -Fusource/generated \
    -Fi"$GEN" -Fisource/g2 -Fisource/units -Fisource/shared -Fisource/generated -Fisource -FU"$U" -o"$OUT/g2" \
    source/g2/g2.dpr > "$OUT/build.log" 2>&1
}
build() {
  compile; rc=$?
  # FPC reports stale compiled units as an internal error; retry once from an empty unit directory, as build.pas does
  if [ $rc -ne 0 ] && grep -a -q -E 'Internal error|Compilation raised exception internally|Error while compiling resources' "$OUT/build.log"; then
    echo 'FPC reported a stale-state error; retrying once from a clean unit directory'
    rm -rf "$U" && mkdir -p "$U" && cp source/generated/*.res "$U/" 2>/dev/null
    compile; rc=$?
  fi
  return $rc
}
build; rc=$?
grep -a -E '(Error|Fatal):' "$OUT/build.log" | head -40
[ $rc -ne 0 ] && exit $rc
# FPC 3.3.1 native TLS: a threadvar address with a constant offset can get an absolute relocation
python3 scripts/g2/tlsscan.py "$U"/*.o > "$OUT/tlsscan.txt"
grep -q '^total 0$' "$OUT/tlsscan.txt" || { echo 'broken threadvar relocations:'; cat "$OUT/tlsscan.txt"; exit 1; }
if [ -z "${G2_NO_SNAPSHOT_BUILD:-}" ]; then
  echo 'var x;' > "$OUT/snap-empty.js"
  G2_SNAPSHOT_OUT="$OUT/snap.bin" G2_NO_SNAPSHOT=1 "$OUT/g2" "$OUT/snap-empty.js" || exit 1
  python3 - "$OUT/snap.bin" "$GEN/G2.PreludeSnapshot.inc" <<'PY'; prc=$?
import sys
b = open(sys.argv[1], 'rb').read()
rows = ',\n    '.join(','.join(str(x) for x in b[i:i + 32]) for i in range(0, len(b), 32))
inc = ('{ generated by scripts/g2/build.sh from G2_SNAPSHOT_OUT: compiled JS preludes (see G2.Snapshot) }\nconst\n'
       f'  G2PreludeSnapshotSize = {len(b)};\n  G2PreludeSnapshot: array[0..{len(b) - 1}] of Byte = (\n    {rows});\n')
try: old = open(sys.argv[2]).read()
except OSError: old = ''
if old != inc:
    open(sys.argv[2], 'w').write(inc)
    print('snapshot changed: rebuilding')
    sys.exit(3)
PY
  [ $prc -ne 0 ] && [ $prc -ne 3 ] && exit 1
  if [ $prc -eq 3 ]; then
    rm -f "$U"/G2.Snapshot.*
    build; rc=$?
    grep -a -E '(Error|Fatal):' "$OUT/build.log" | head -40
    [ $rc -ne 0 ] && exit $rc
    python3 scripts/g2/tlsscan.py "$U"/*.o > "$OUT/tlsscan.txt"
    grep -q '^total 0$' "$OUT/tlsscan.txt" || { echo 'broken threadvar relocations:'; cat "$OUT/tlsscan.txt"; exit 1; }
  fi
fi
echo "build ok: $OUT/g2"
