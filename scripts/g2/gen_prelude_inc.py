#!/usr/bin/env python3
"""gen_prelude_inc.py SRC.js OUT.inc CONSTNAME: a JS prelude as a Pascal UnicodeString constant (one line each)."""
import sys
src, out, name = sys.argv[1:4]
lines = open(src, encoding='utf-8').read().rstrip('\n').split('\n')
parts = []
for l in lines:
    assert all(ord(c) < 128 for c in l), 'non-ASCII in prelude: ' + l
    parts.append("    '" + l.replace("'", "''") + "'#10")
open(out, 'w').write('{ generated by t/lang/gen_prelude_inc.py from ' + src.split('/')[-1] + ' }\nconst\n  ' + name +
                     ' =\n' + ' +\n'.join(parts) + ';\n')
